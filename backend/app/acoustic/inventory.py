def is_vowel(ipa: str) -> bool:
    return ipa in VOWELS


def tip_for(ipa: str) -> tuple[str, str]:
    """(짧은 이름, 안내). 사전에 없으면 음소 기호를 그대로 이름으로 쓴다."""
    if ipa in TIPS_KO:
        return TIPS_KO[ipa]
    return (ipa, f"'{ipa}' 소리를 천천히 한 번 더 들어 보고 따라 해 보세요.")
